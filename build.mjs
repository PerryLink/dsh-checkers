#!/usr/bin/env node
/** Regenerate the suite manifest from the 53 compliance plugin package.json/cordis.patch.yml files. */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
const root = dirname(new URL(import.meta.url).pathname)
const checkers = join(root, '..', '..', 'checkers')
const rows = []
for (const d of readdirSync(checkers).sort()) {
  const pkgPath = join(checkers, d, 'package.json')
  if (!existsSync(pkgPath)) continue
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
  if (pkg.private) continue
  const patch = readFileSync(join(checkers, d, 'cordis.patch.yml'), 'utf8')
  const id = /- id:\s*(\S+)/.exec(patch)?.[1]
  const name = /\n\s*name:\s*(\S+)/.exec(patch)?.[1]
  if (!id || !name) throw new Error(`no row in ${d}`)
  rows.push({ id, name, version: pkg.version })
}
const pkgPath = join(root, 'package.json')
const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'))
pkg.dependencies = Object.fromEntries(rows.map(r => [r.name, r.version]))
writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`)
writeFileSync(join(root, 'cordis.patch.yml'), `# Generated by build.mjs — one insert row per compliance plugin.\n# Install @perrylink/dsh-checkers to add all ${rows.length} compliance checkers as one bundle layer.\n- insert:\n${rows.map(r => `    - id: ${r.id}\n      name: ${r.name}`).join('\n')}\n`)
writeFileSync(join(root, 'checkers.json'), `${JSON.stringify(rows, null, 2)}\n`)
console.log(`generated ${rows.length} checker rows`)
